#!/usr/bin/env node
/** Build the small resource index and accelerated GIF. Raw media is never embedded in JS. */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const client = new URL('../lib/client.js', import.meta.url), root = new URL('../assets/', import.meta.url);
const manifestURL = new URL('manifest.json', root), manifest = JSON.parse(readFileSync(manifestURL, 'utf8'));
const gif = readFileSync(new URL(manifest.gif.source, root));
const playbackRate = manifest.gif.playbackRate, playbackGif = Buffer.from(gif);
const checking = process.argv.includes('--check');
// 按 GIF 数据块读取帧数与真实时长，不扫描压缩像素中的字节模式。
if (!/^GIF8[79]a$/.test(gif.subarray(0, 6).toString())) throw new Error('开机素材必须是 GIF');
const width = gif.readUInt16LE(6), height = gif.readUInt16LE(8);
let offset = 13 + (gif[10] & 0x80 ? 3 * (2 ** ((gif[10] & 7) + 1)) : 0);
const blockStart = offset;
let frames = 0, durationMs = 0, delayMs = 0, playbackDelayMs = 0, cycleDurationMs = 0, hasLoop = false;
const skipBlocks = () => {
 while (offset < gif.length) {
  const size = gif[offset++];
  if (!size) return;
  offset += size;
 }
 throw new Error('GIF 数据块未结束');
};
while (offset < gif.length) {
 const type = gif[offset++];
 if (type === 0x3b) break;
 if (type === 0x21) {
  const extension = gif[offset++];
  if (extension === 0xf9) {
   if (gif[offset] !== 4) throw new Error('GIF 控制块无效');
   delayMs = gif.readUInt16LE(offset + 2) * 10;
   const fastDelay = delayMs / 10 / playbackRate;
   if (!Number.isInteger(fastDelay) || fastDelay < 2) throw new Error('GIF 两倍速帧延迟必须为至少 20ms 的整数刻度');
   playbackGif.writeUInt16LE(fastDelay, offset + 2); playbackDelayMs = fastDelay * 10;
  }
  if (extension === 0xff && gif[offset] === 11 && ['NETSCAPE2.0', 'ANIMEXTS1.0'].includes(gif.subarray(offset + 1, offset + 12).toString())) {
   if (gif[offset + 12] !== 3 || gif[offset + 13] !== 1) throw new Error('GIF 循环扩展无效');
   playbackGif.writeUInt16LE(0, offset + 14); hasLoop = true;
  }
  skipBlocks();
 } else if (type === 0x2c) {
  const packed = gif[offset + 8]; offset += 9;
  if (packed & 0x80) offset += 3 * (2 ** ((packed & 7) + 1));
  offset++; skipBlocks();
  frames++; durationMs += delayMs; cycleDurationMs += playbackDelayMs; delayMs = playbackDelayMs = 0;
 } else throw new Error('GIF 出现未知数据块');
}
if (!frames || !durationMs) throw new Error('GIF 需要至少一帧与有效时长');
if (cycleDurationMs * playbackRate !== durationMs) throw new Error('GIF 加速后时长不一致');
const loopedGif = hasLoop ? playbackGif : Buffer.concat([playbackGif.subarray(0, blockStart), Buffer.from('21ff0b4e45545343415045322e300301000000', 'hex'), playbackGif.subarray(blockStart)]);
const fastURL = new URL(manifest.assets.boot.file, root);
if (checking) {
 if (!existsSync(fastURL) || !readFileSync(fastURL).equals(loopedGif)) throw new Error('Accelerated GIF is stale; run npm run build');
} else {mkdirSync(new URL('animations/', root), {recursive:true}); writeFileSync(fastURL, loopedGif);}
manifest.gif = {...manifest.gif, width, height, frames, durationMs, cycleDurationMs};
const source = readFileSync(client, 'utf8');
const renderer = source.match(/function createContourRenderer\(\) \{[\s\S]*?\n\t\t\}/)?.[0];
if (!renderer) throw new Error('Missing contour renderer');
const worker = '// Generated by tools/build-assets.mjs; edit createContourRenderer in lib/client.js.\nconst render = (' + renderer + ')();\nself.onmessage = ({data}) => self.postMessage(render(data));\n';
const workerURL = new URL(manifest.assets.contourWorker.file, root);
if (checking) {
 if (!existsSync(workerURL) || readFileSync(workerURL, 'utf8') !== worker) throw new Error('Worker is stale; run npm run build');
} else {mkdirSync(new URL('workers/', root), {recursive:true}); writeFileSync(workerURL, worker);}
const definitions = [];
for (const [key, asset] of Object.entries(manifest.assets)) {
 const data = readFileSync(new URL(asset.file, root));
 asset.bytes = data.length; asset.sha256 = createHash('sha256').update(data).digest('hex');
 if (asset.type === 'image/png' && data.subarray(0,8).toString('hex') !== '89504e470d0a1a0a') throw new Error('Invalid PNG: ' + asset.file);
 if (asset.type === 'audio/mpeg' && data.subarray(0,3).toString() !== 'ID3' && data[0] !== 0xff) throw new Error('Invalid MP3: ' + asset.file);
 const value = asset.inline ? data.toString('utf8') : manifest.basePath + asset.file + '?v=' + asset.sha256.slice(0,12);
 definitions.push('\t\t\t' + key + ': ' + JSON.stringify(value) + ',');
}
const start = '\t\t// BEGIN GENERATED ASSET INDEX', end = '\t\t// END GENERATED ASSET INDEX';
const block = [start, '\t\t// Generated by tools/build-assets.mjs: small SVG markup and versioned same-origin URLs.', '\t\tconst BRAND_ASSETS = Object.freeze({', ...definitions,
 `\t\t\twidth: ${width}, height: ${height}, frames: ${frames}, durationMs: ${durationMs}, cycleDurationMs: ${cycleDurationMs}, playbackRate: ${playbackRate},`, '\t\t});', end].join('\n');
const a = source.indexOf(start), b = source.indexOf(end, a);
if (a < 0 || b < 0) throw new Error('Missing asset index markers');
const next = source.slice(0,a) + block + source.slice(b + end.length), json = JSON.stringify(manifest, null, 2) + '\n';
if (checking) {
 if (source !== next || readFileSync(manifestURL,'utf8') !== json) throw new Error('Asset index is stale; run npm run build');
 console.log(`✓ ${definitions.length} assets verified; GIF ${playbackRate}× / ${cycleDurationMs}ms / opening ${durationMs}ms`);
} else {writeFileSync(client,next); writeFileSync(manifestURL,json); console.log(`✓ Built ${definitions.length} versioned assets; client ${Buffer.byteLength(next)} bytes`);}
